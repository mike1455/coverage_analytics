// Сопоставление адресов МЖИ (форматы из реального реестра) с адресами зданий OSM (как они записаны в OSM Москвы).
import test from 'node:test';
import assert from 'node:assert/strict';
import { parseAddress, streetBag, normHn, buildIndex, matchAddress } from '../core/addrmatch.js';

test('разбор адресов МЖИ: БТИ, ГАР, Зеленоград, уточнения в скобках', () => {
  const cases = [
    ['Лескова ул., д.5', 'лескова улица', ['5']],
    ['Хорошевское шоссе, д.76, к.4', 'хорошевское шоссе', ['76к4']],
    ['Басманный 1-й пер., д.5/20,  стр.1', '1 басманный переулок', ['5/20с1']],
    ['Шмитовский пр., д.16,  стр.2', 'проезд шмитовский', ['16с2']],
    ['Зеленый просп., д.25, к.3', 'зеленый проспект', ['25к3']],
    ['Бочвара Академика ул., д.5, к.2', 'академика бочвара улица', ['5к2']],
    ['Зеленоград, к.418', 'зеленоград', ['418', 'к418']],
    ['Зеленоград г. (Зеленоград г.), к.2315а', 'зеленоград', ['2315а', 'к2315а']],
    ['Российская Федерация, город Москва, внутригородская территория муниципальный округ Якиманка, Софийская набережная, дом 24/2, строение 2', 'набережная софийская', ['24/2с2']],
    ['город Москва, улица Поленова, дом 4', 'поленова улица', ['4']],
    ['Ватутинская 3-я ул. д. 6', '3 ватутинская улица', ['6']],
    ['Тихая ул., д.4, к.А', 'тихая улица', ['4ка', '4а']],
  ];
  for (const [addr, bag, keys] of cases) {
    const p = parseAddress(addr);
    assert.equal(streetBag(p.street), bag, addr);
    assert.deepEqual(p.keys, keys, addr);
  }
  assert.equal(parseAddress('Чехова ул. (Щербинка г.), д.4').qualifier, 'Щербинка г.');
  assert.equal(parseAddress('Красная Пахра сел. (Краснопахорское), д.2').street, 'Красная Пахра сел.');
});

test('номер дома OSM приводится к одному виду', () => {
  assert.equal(normHn('76 к4'), '76к4');
  assert.equal(normHn('76, корп. 4'), '76к4');
  assert.equal(normHn('5/20 стр. 1'), '5/20с1');
  assert.equal(normHn('12А'), '12а');
  assert.equal(normHn('7 корпус 1 строение 2'), '7к1с2');
});

// [type, street, housenumber, place, city, lat, lon]
const OSM = [
  ['w', 'улица Лескова', '5', '', '', 55.889, 37.593],
  ['w', 'Хорошёвское шоссе', '76к4', '', '', 55.776, 37.528],
  ['w', '1-й Басманный переулок', '5/20с1', '', '', 55.771, 37.668],
  ['w', 'Шмитовский проезд', '16с2', '', '', 55.756, 37.548],
  ['w', 'Зелёный проспект', '25к3', '', '', 55.751, 37.811],
  ['w', 'улица Академика Бочвара', '5 к2', '', '', 55.806, 37.477],
  ['w', '', 'к418', '', 'Зеленоград', 55.990, 37.215],
  ['w', 'Софийская набережная', '24/2с2', '', '', 55.746, 37.618],
  ['n', 'Софийская набережная', '24/2с2', '', '', 55.7461, 37.6182], // точка-POI рядом со зданием
  ['w', 'улица Чехова', '4', '', 'Щербинка', 55.503, 37.564],
  ['w', 'улица Чехова', '4', '', 'Троицк', 55.485, 37.305],
  ['w', 'Центральная улица', '1', '', '', 55.60, 37.40],
  ['w', 'Центральная улица', '1', '', 'Московский', 55.60, 37.35],
  ['w', 'Садовая улица', '3', '', 'Внуково', 55.62, 37.30],
  ['w', 'Садовая улица', '3', '', 'Кокошкино', 55.60, 37.17],
  ['w', '', '7', '', 'посёлок Газопровод', 55.58, 37.48],
  ['w', 'улица Газопровод', '7', '', '', 55.63, 37.55],
  ['w', 'Тихая улица', '4А', '', '', 55.83, 37.47],
];

test('координаты находятся по адресу МЖИ, неоднозначные дома не привязываются', () => {
  const idx = buildIndex(OSM);
  const ok = (addr, lat) => {
    const r = matchAddress(idx, addr);
    assert.equal(r.status, 'ok', `${addr}: ${JSON.stringify(r)}`);
    if (lat) assert.equal(r.lat, lat, addr);
    return r;
  };
  ok('Лескова ул., д.5', 55.889);
  ok('Хорошевское шоссе, д.76, к.4', 55.776);
  ok('Басманный 1-й пер., д.5/20,  стр.1', 55.771);
  ok('Шмитовский пр., д.16,  стр.2', 55.756);
  ok('Зеленый просп., д.25, к.3', 55.751);
  ok('Бочвара Академика ул., д.5, к.2', 55.806);
  ok('Зеленоград, к.418', 55.990);
  assert.equal(ok('Российская Федерация, город Москва, внутригородская территория муниципальный округ Якиманка, Софийская набережная, дом 24/2, строение 2').type, 'w', 'здание важнее точки рядом');
  ok('Чехова ул. (Щербинка г.), д.4', 55.503); // уточнение в скобках выбирает город
  assert.equal(matchAddress(idx, 'Чехова ул., д.4').status, 'ambiguous', 'без уточнения два разных города');
  ok('Центральная ул., д.1', 55.60); // без уточнения: дом в самой Москве, а не в посёлке
  assert.equal(matchAddress(idx, 'Центральная ул., д.1').lon, 37.40);
  assert.equal(matchAddress(idx, 'Садовая ул., д.3').status, 'ambiguous');
  ok('Газопровод пос. (Сосенское), д.7', 55.58); // посёлок, а не «улица Газопровод»
  ok('Тихая ул., д.4, к.А', 55.83);
  assert.equal(matchAddress(idx, 'Лескова ул., д.7').status, 'notfound', 'номер дома должен совпасть точно');
  assert.equal(matchAddress(idx, 'Хорошевское шоссе, д.76').status, 'notfound', 'дом без корпуса не равен корпусу');
  assert.equal(matchAddress(idx, 'Железнодорожная 1-я улица, в.3').status, 'unparsed');
});
